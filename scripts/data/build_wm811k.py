"""Create small, deterministic, lot-separated WM-811K samples from the Kaggle zip.

Run with the bundled Python runtime (pandas and numpy required):
  python scripts/data/build_wm811k.py /path/to/wafer-wm811k.zip
The Kaggle listing marks this upload CC0; upstream provenance was not verified.
"""

import hashlib
import json
import pickle
import random
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[2]
LABELS = ["none", "Center", "Donut", "Edge-Loc", "Edge-Ring", "Loc", "Near-full", "Random", "Scratch"]
SEED = 8112026
SIZE = 32

# This public 2018 pickle refers to modules removed from pandas 2.
for name in ["pandas.indexes", "pandas.indexes.base", "pandas.indexes.range", "pandas.indexes.datetimes", "pandas.indexes.multi"]:
    sys.modules[name] = __import__(name.replace("pandas.indexes", "pandas.core.indexes"), fromlist=["*"])


def resize(grid):
    height, width = grid.shape
    ys = np.minimum((np.arange(SIZE) + 0.5) * height // SIZE, height - 1).astype(int)
    xs = np.minimum((np.arange(SIZE) + 0.5) * width // SIZE, width - 1).astype(int)
    return grid[np.ix_(ys, xs)].astype(np.uint8).tolist()


def reservoir_add(bucket, item, count, rng, cap):
    count += 1
    if len(bucket) < cap:
        bucket.append(item)
    else:
        place = rng.randrange(count)
        if place < cap:
            bucket[place] = item
    return count


def main(archive):
    rng = random.Random(SEED)
    with zipfile.ZipFile(archive) as z, z.open("LSWMD.pkl") as source:
        frame = pickle.load(source, encoding="latin1")
    chosen = defaultdict(list)
    seen = Counter()
    available = Counter()
    lots = defaultdict(set)
    for index, row in enumerate(frame.itertuples(index=False)):
        raw = row.failureType
        if raw.size != 1:
            continue
        label = str(raw.flat[0])
        if label not in LABELS:
            continue
        lot = str(row.lotName)
        split = "holdout" if int(hashlib.sha256(lot.encode()).hexdigest()[:8], 16) % 5 == 0 else "train"
        key = (split, label)
        available[key] += 1
        lots[key].add(lot)
        cap = 80 if split == "train" else 40
        seen[key] = reservoir_add(chosen[key], (index, lot), seen[key], rng, cap)

    records = {}
    for split in ["train", "holdout"]:
        records[split] = []
        for label in LABELS:
            for index, lot in sorted(chosen[(split, label)]):
                records[split].append({"id": f"WM-{index:06d}", "label": label, "lot": lot, "grid": resize(frame.iloc[index].waferMap)})

    assert not ({row["lot"] for row in records["train"]} & {row["lot"] for row in records["holdout"]})

    training = [{key: value for key, value in row.items() if key != "lot"} for row in records["train"]]
    (ROOT / "src/model/training.ts").write_text("// Generated by scripts/data/build_wm811k.py; source credit in public/data/metrics.json.\nexport const training: {id:string,label:string,grid:number[][]}[] = " + json.dumps(training, separators=(",", ":")) + ";\n")
    data = ROOT / "data"
    data.mkdir(exist_ok=True)
    (data / "holdout.json").write_text(json.dumps(records["holdout"], separators=(",", ":")))
    demo = [{key: value for key, value in next(row for row in records["holdout"] if row["label"] == label).items() if key != "lot"} for label in LABELS]
    (ROOT / "src/model/examples.ts").write_text("// Held-out examples; generated by scripts/data/build_wm811k.py.\nexport const demoExamples: {id:string,label:string,grid:number[][]}[] = " + json.dumps(demo, separators=(",", ":")) + ";\n")
    (data / "sample_manifest.json").write_text(json.dumps({
        "seed": SEED, "resize": "32x32 nearest-neighbor cell-center", "lotSplit": "SHA-256 first 32 bits of lotName modulo 5; residue 0 holdout",
        "caps": {"trainPerClass": 80, "holdoutPerClass": 40},
        "availableRows": {f"{split}/{label}": available[(split, label)] for split in ["train", "holdout"] for label in LABELS},
        "availableLots": {f"{split}/{label}": len(lots[(split, label)]) for split in ["train", "holdout"] for label in LABELS},
        "sampledRows": {split: dict(Counter(row["label"] for row in records[split])) for split in ["train", "holdout"]},
        "sampledLots": {split: len(set(row["lot"] for row in records[split])) for split in ["train", "holdout"]},
    }, indent=2))
    print("samples", {split: len(records[split]) for split in records}, flush=True)


if __name__ == "__main__":
    main(sys.argv[1])
