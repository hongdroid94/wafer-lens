"""One preset training-size comparison on v2 lot-separated partitions."""
import hashlib
import json
import pickle
import random
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
LABELS = ["none", "Center", "Donut", "Edge-Loc", "Edge-Ring", "Loc", "Near-full", "Random", "Scratch"]
for name in ["pandas.indexes", "pandas.indexes.base", "pandas.indexes.range", "pandas.indexes.datetimes", "pandas.indexes.multi"]:
    sys.modules[name] = __import__(name.replace("pandas.indexes", "pandas.core.indexes"), fromlist=["*"])

def resize(grid):
    height, width = grid.shape
    ys = np.minimum((np.arange(32) + 0.5) * height // 32, height - 1).astype(int)
    xs = np.minimum((np.arange(32) + 0.5) * width // 32, width - 1).astype(int)
    return grid[np.ix_(ys, xs)].astype(np.uint8).tolist()

def main(archive):
    rng = random.Random(8112027)
    with zipfile.ZipFile(archive) as z, z.open("LSWMD.pkl") as source:
        frame = pickle.load(source, encoding="latin1")
    sampled, seen, available = defaultdict(list), Counter(), Counter()
    for index, row in enumerate(frame.itertuples(index=False)):
        if row.failureType.size != 1:
            continue
        label = str(row.failureType.flat[0])
        if label not in LABELS:
            continue
        residue = int(hashlib.sha256(str(row.lotName).encode()).hexdigest()[:8], 16) % 5
        split = {1: "validation", 2: "final", 3: "train", 4: "train"}.get(residue)
        if not split:
            continue
        key = (split, label)
        available[key] += 1
        seen[key] += 1
        cap = 160 if split == "train" else 40
        item = (index, str(row.lotName))
        if len(sampled[key]) < cap:
            sampled[key].append(item)
        else:
            position = rng.randrange(seen[key])
            if position < cap:
                sampled[key][position] = item
    output = {}
    for split in ["train", "validation", "final"]:
        output[split] = [{"id": f"WM-{index:06d}", "label": label, "grid": resize(frame.iloc[index].waferMap), "lot": lot}
                         for label in LABELS for index, lot in sampled[(split, label)]]
    assert len(set(row["lot"] for row in output["train"]) & set(row["lot"] for row in output["validation"])) == 0
    assert len(set(row["lot"] for row in output["train"]) & set(row["lot"] for row in output["final"])) == 0
    data = ROOT / "data"
    for split, rows in output.items():
        (data / f"explore_{split}.json").write_text(json.dumps(rows, separators=(",", ":")))
    train = [{key: value for key, value in row.items() if key != "lot"} for row in output["train"]]
    demo = [{key: value for key, value in next(row for row in output["final"] if row["label"] == label).items() if key != "lot"} for label in LABELS]
    (ROOT / "src/model/training.ts").write_text("// Generated by scripts/data/explore_more_training.py; source credit in public/data/metrics.json.\nexport const training: {id:string,label:string,grid:number[][]}[] = " + json.dumps(train, separators=(",", ":")) + ";\n")
    (ROOT / "src/model/examples.ts").write_text("// v2 evaluation examples; generated by scripts/data/explore_more_training.py.\nexport const demoExamples: {id:string,label:string,grid:number[][]}[] = " + json.dumps(demo, separators=(",", ":")) + ";\n")
    print({split: dict(Counter(row["label"] for row in rows)) for split, rows in output.items()}, flush=True)

if __name__ == "__main__":
    main(sys.argv[1])
